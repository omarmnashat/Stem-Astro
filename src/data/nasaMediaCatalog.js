export function resolveModuleMedia(actionId, planet = 'moon') {
  const media = MODULE_REAL_MEDIA[actionId] || MODULE_REAL_MEDIA.shield;
  const source = NASA_OFFICIAL_SOURCES[media.sourceKey] || NASA_OFFICIAL_SOURCES.artemis;
  const isMars = planet === 'mars';

  const activeNasaId = isMars && media.marsNasaId ? media.marsNasaId : media.nasaId;
  const imgUrl = isMars && media.marsImage ? media.marsImage : media.image;
  const activeTitle = isMars && media.marsTitle ? media.marsTitle : media.title;
  const activeMission = isMars && media.marsMission ? media.marsMission : media.mission;
  const activeFact = isMars && media.marsFact ? media.marsFact : media.fact;
  const activeFallbackQuery = isMars && media.marsFallbackQuery ? media.marsFallbackQuery : media.fallbackApiQuery;

  return {
    ...media,
    title: activeTitle,
    mission: activeMission,
    fact: activeFact,
    fallbackApiQuery: activeFallbackQuery,
    nasaId: activeNasaId,
    imgUrl,
    nasaDetailsUrl: activeNasaId ? `https://images.nasa.gov/details/${activeNasaId}` : source.url,
    fallbackImgUrl: FALLBACK_NASA_IMAGE,
    source,
  };
}